# Makes src/core/include/lycan/version.h from the VERSION file in the root (the single source of truth; the CLI, the App, the resource files and the About page use it).
# -Check: only checks that version.h matches VERSION (fails if not), for the packaging scripts and CI.
param([switch]$Check)
$ErrorActionPreference = "Stop"
$root = Split-Path $PSScriptRoot -Parent
$ver = (Get-Content (Join-Path $root "VERSION") -Raw).Trim()
if ($ver -notmatch '^(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z.]+))?$') { throw "The format of VERSION must be major.minor.patch(-pre-release): $ver" }
$major, $minor, $patch, $pre = [int]$Matches[1], [int]$Matches[2], [int]$Matches[3], $Matches[4]

$header = @"
// Generated by scripts/sync-version.ps1 from the VERSION file in the root; do not edit by hand.
#pragma once
#define LYCAN_VERSION_MAJOR $major
#define LYCAN_VERSION_MINOR $minor
#define LYCAN_VERSION_PATCH $patch
#define LYCAN_VERSION_STRING "$ver"
#define LYCAN_VERSION_WSTRING L"$ver"
// four-part version for the resource file / MSIX (the fourth part is always 0)
#define LYCAN_VERSION_RC $major,$minor,$patch,0
#define LYCAN_VERSION_RC_STRING "$major.$minor.$patch.0"
"@
$path = Join-Path $root "src\core\include\lycan\version.h"
$current = if (Test-Path $path) { (Get-Content $path -Raw -Encoding UTF8) } else { "" }
if ($Check) {
    if ($current.Replace("`r`n", "`n") -ne ($header + "`n").Replace("`r`n", "`n")) { throw "version.h does not match VERSION ($ver), run scripts\sync-version.ps1" }
    Write-Host "version.h matches VERSION ($ver)"; return
}
[IO.File]::WriteAllText($path, ($header + "`n"), (New-Object Text.UTF8Encoding($false)))
Write-Host "Updated $path ($ver)"
